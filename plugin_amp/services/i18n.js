export function lang(ctx) {
  return setting(ctx, 'language', 'en') === 'de' ? 'de' : 'en';
}

export function t(L, key, params = {}) {
  const text = TEXT[L]?.[key] ?? TEXT.en[key] ?? key;
  return String(text).replace(/\{(\w+)\}/g, (all, k) => (k in params ? String(params[k]) : all));
}
