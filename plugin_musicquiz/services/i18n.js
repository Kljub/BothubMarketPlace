/** The text of a key with {placeholders} filled. */
export function t(lang, key, params = {}) {
  const text = TEXT[lang]?.[key] ?? TEXT.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (all, k) => (k in params ? String(params[k]) : all));
}

/** The shown name of a source key ("80s" stays "80s"). */
export const sourceName = (lang, key) => SOURCE_NAMES[lang]?.[key] ?? SOURCE_NAMES.en[key] ?? key;
